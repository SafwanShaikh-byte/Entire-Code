package Varibles;

public class DefaultvalueofVariables {
	
	int number;       // default 0
    boolean status;   // default false
    String text; 

	public static void main(String[] args) 
	{
	
		DefaultvalueofVariables obj = new DefaultvalueofVariables();
		
		System.out.println("int -> " +  obj.number);
		System.out.println("int -> " +  obj.status);
		System.out.println("int -> " +  obj.text);
	}

}
