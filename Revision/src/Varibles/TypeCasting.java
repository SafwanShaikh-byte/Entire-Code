package Varibles;

public class TypeCasting {
	
	public static void main(String[] args) {
		
		int x =100;
		
		double d =x;
		String s = String.valueOf(x);
		

        System.out.println("Integer: " + x);
        System.out.println("Double: " + d);
        System.out.println("String: " + s);
	}

}
